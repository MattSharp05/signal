// Generates the seed migration for the `sources` table from the connector registry.
// Usage: npx tsx scripts/gen-sources-sql.ts > supabase/migrations/20261119000100_seed_sources.sql
import { defaultSourceRecords } from '../supabase/functions/_shared/core/connectors/index.ts'

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a: string[]) => `'{${a.map((x) => `"${x}"`).join(',')}}'`
const rows = defaultSourceRecords().map(
  (s) =>
    `  (${q(s.id)}, ${q(s.name)}, ${q(s.kind)}, ${q(s.role)}, ${q(s.status)}, ${s.enabled}, ${s.refreshMinutes}, ${q(s.homepage)}, ${q(s.docsUrl)}, ${q(s.notes)}, ${arr(s.credentialEnv)}, ${arr(s.runsIn)}, ${q(JSON.stringify(s.config))}::jsonb)`,
)
console.log(`-- Generated by scripts/gen-sources-sql.ts — source catalog (status reflects what actually works without credentials).
insert into public.sources (id, name, kind, role, status, enabled, refresh_minutes, homepage, docs_url, notes, credential_env, runs_in, config) values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, kind = excluded.kind, role = excluded.role, homepage = excluded.homepage,
  docs_url = excluded.docs_url, notes = excluded.notes, credential_env = excluded.credential_env, runs_in = excluded.runs_in;`)
